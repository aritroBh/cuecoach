"""Inline mlx-swift's precompiled (non-JIT) Metal kernels into one source string.

The Metal Toolchain (offline `metal` compiler) is not installed on this Mac, so instead of a build-time
default.metallib we compile these kernels at runtime with MTLDevice.newLibrary(source:). Output is a C++
source file defining `mlx_default_metal_source()` for the patched device.cpp.
Usage: python3 inline_metal.py <mlx-swift>/Source/Cmlx <out.cpp>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) / "mlx-generated" / "metal"
out = Path(sys.argv[2])
files = sorted(p for p in root.rglob("*.metal"))
seen: set[Path] = set()
inc = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
pragma_once = re.compile(r"^\s*#\s*pragma\s+once")


def expand(path: Path) -> list[str]:
    path = path.resolve()
    if path in seen:
        return []
    seen.add(path)
    lines = []
    for line in path.read_text().splitlines():
        m = inc.match(line)
        if m:
            name = m.group(1)
            cands = [path.parent / name, root / name]
            target = next((c for c in cands if c.exists()), None)
            if target is None:
                raise SystemExit(f"cannot resolve {name} from {path}")
            lines += expand(target)
        elif pragma_once.match(line):
            continue
        else:
            lines.append(line)
    return lines


outdir = out.parent
entries = []
for f in files:
    seen.clear()
    text = "\n".join(expand(f)) + "\n"
    name = str(f.relative_to(root))
    entries.append((name, text))
    (outdir / (f.stem + ".inlined.metal")).write_text(text)


def raw(text: str) -> str:
    chunks = [text[i : i + 30000] for i in range(0, len(text), 30000)]
    return " + ".join(f'std::string(R"MLXSRC({c})MLXSRC")' for c in chunks)


items = ",\n".join(f'      {{"{n}", {raw(t)}}}' for n, t in entries)
out.write_text(
    "// Generated by tools/vlm-bench/vendor-patches/inline_metal.py - do not edit.\n"
    "#include <string>\n#include <utility>\n#include <vector>\n"
    "namespace mlx::core::metal {\n"
    "const std::vector<std::pair<std::string, std::string>>& mlx_runtime_metal_sources() {\n"
    "  static const std::vector<std::pair<std::string, std::string>> v = {\n"
    f"{items}\n"
    "  };\n"
    "  return v;\n"
    "}\n"
    "}\n"
)
print(f"{len(entries)} kernel files -> {out}")
